// Generates the typed API client from the BACKEND's OpenAPI artifact (ADR-0006 §3).
//   npm run api:generate   pin ../Call360-backend/contracts/generated/openapi.json and regenerate types
//   npm run api:check      fail on drift: generated types, pinned file vs lock, pinned vs sibling backend
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const backend = resolve(root, '../Call360-backend');
const sibling = resolve(backend, 'contracts/generated/openapi.json');
const pinned = resolve(root, 'src/api/openapi.pinned.json');
const lockFile = resolve(root, 'src/api/contract.lock.json');
const typesFile = resolve(root, 'src/api/generated/schema.d.ts');
const sha = (text) => createHash('sha256').update(text).digest('hex');
const header = '// GENERATED by scripts/api-generate.mjs from the pinned backend OpenAPI. Do not edit.\n';

async function render(specText) {
  const ast = await openapiTS(JSON.parse(specText));
  return header + astToString(ast);
}

const check = process.argv.includes('--check');
if (!check) {
  if (!existsSync(sibling)) throw new Error(`backend artifact not found: ${sibling}`);
  const spec = readFileSync(sibling, 'utf8');
  let baseSha = null;
  try { baseSha = execFileSync('git', ['-C', backend, 'rev-parse', 'HEAD']).toString().trim(); } catch { /* not a repo */ }
  writeFileSync(pinned, spec);
  writeFileSync(lockFile, JSON.stringify({ backend_repo: 'Call360-backend', backend_base_sha: baseSha,
    backend_manifest_sha256: null, openapi_sha256: sha(spec) }, null, 2) + '\n');
  writeFileSync(typesFile, await render(spec));
  console.log(`Pinned backend OpenAPI ${sha(spec)} and regenerated ${typesFile.replace(root + '/', '')}`);
} else {
  const problems = [];
  const spec = readFileSync(pinned, 'utf8');
  const lock = JSON.parse(readFileSync(lockFile, 'utf8'));
  if (lock.openapi_sha256 !== sha(spec)) problems.push('pinned OpenAPI does not match contract.lock.json');
  if (readFileSync(typesFile, 'utf8') !== await render(spec)) problems.push('generated types drifted; run npm run api:generate');
  if (existsSync(sibling) && readFileSync(sibling, 'utf8') !== spec) problems.push('pinned OpenAPI differs from the backend artifact');
  if (problems.length) { console.error('api:check FAILED\n - ' + problems.join('\n - ')); process.exit(1); }
  console.log(`api:check OK (openapi ${lock.openapi_sha256})`);
}
